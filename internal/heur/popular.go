package heur

// popularExt is one widely installed extension used as a typosquat target.
type popularExt struct {
	id          string // "publisher.name", lower-case
	displayName string // marketplace display name; "" when not distinctive
}

// publisher returns the part of the id before the first dot.
func (p popularExt) publisher() string {
	for i := 0; i < len(p.id); i++ {
		if p.id[i] == '.' {
			return p.id[:i]
		}
	}
	return p.id
}

